#!/usr/bin/env python3
"""Convert the Sigma rules to Microsoft Defender XDR / Sentinel KQL and Splunk SPL with pySigma.

    python tools/convert.py           # writes conversions/<rule>.kql and .spl
    python tools/convert.py --check   # exit 1 if the committed files are out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

from sigma.backends.kusto import KustoBackend
from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.pipelines.microsoftxdr import microsoft_xdr_pipeline
from sigma.pipelines.splunk import splunk_windows_pipeline

ROOT = Path(__file__).resolve().parents[1]


# Defender XDR's Advanced Hunting tables have no Sysmon-style process-access event
# (GrantedAccess on a handle to lsass), so that rule is converted for Splunk only.
KQL_UNSUPPORTED = {"process_access"}


def render() -> dict[str, str]:
    out = {}
    for path in sorted((ROOT / "rules").glob("*.yml")):
        text = path.read_text(encoding="utf-8")
        # Pipelines modify the parsed rule, so every backend gets a fresh parse.
        category = SigmaCollection.from_yaml(text).rules[0].logsource.category
        if category not in KQL_UNSUPPORTED:
            kql = KustoBackend(processing_pipeline=microsoft_xdr_pipeline())
            out[f"{path.stem}.kql"] = (f"// {path.name} - Microsoft Defender XDR / Sentinel "
                                       f"(generated by tools/convert.py)\n"
                                       + "\n".join(kql.convert(SigmaCollection.from_yaml(text))) + "\n")
        spl = SplunkBackend(processing_pipeline=splunk_windows_pipeline())
        out[f"{path.stem}.spl"] = (f"``` {path.name} - Splunk, Sysmon field names "
                                   f"(generated by tools/convert.py) ```\n"
                                   + "\n".join(spl.convert(SigmaCollection.from_yaml(text))) + "\n")
    return out


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    files = render()
    target = ROOT / "conversions"
    if "--check" in argv:
        stale = [n for n, body in files.items()
                 if not (target / n).exists() or (target / n).read_text(encoding="utf-8") != body]
        for n in stale:
            print(f"out of date: conversions/{n}")
        return 1 if stale else 0
    target.mkdir(exist_ok=True)
    for name, body in files.items():
        (target / name).write_text(body, encoding="utf-8")
        print(f"wrote conversions/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
